#!/usr/bin/env node
/**
 * scripts/graphql-emit-documents.mjs
 * 
 * Emit src/lib/graphql/__generated__/documents.ts — one string constant per
 * operation file under src/lib/graphql/operations/.
 * 
 * Turbopack has no raw loader; emitting a plain TypeScript module eliminates
 * any bundler dependency or runtime parsing overhead.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse, print } from "graphql";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, "..");
const OPERATIONS_DIR = path.join(ROOT_DIR, "src", "lib", "graphql", "operations");
const OUT_FILE = path.join(ROOT_DIR, "src", "lib", "graphql", "__generated__", "documents.ts");

function* walk(dir) {
  if (!fs.existsSync(dir)) return;
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      yield* walk(full);
    } else if (entry.name.endsWith(".graphql")) {
      yield full;
    }
  }
}

function main() {
  if (!fs.existsSync(OPERATIONS_DIR)) {
    console.warn(`[graphql-emit] No operations dir found at ${OPERATIONS_DIR}`);
    return;
  }

  const outDir = path.dirname(OUT_FILE);
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  const files = [...walk(OPERATIONS_DIR)].sort();
  const exports = [];

  for (const file of files) {
    const raw = fs.readFileSync(file, "utf-8");
    const doc = parse(raw);
    const opDef = doc.definitions.find(
      (d) => d.kind === "OperationDefinition" && d.name
    );

    if (!opDef || !opDef.name) {
      console.warn(`[graphql-emit] Skipping anonymous operation in ${file}`);
      continue;
    }

    const opName = opDef.name.value;
    const constName = `${opName}Document`;
    const printed = print(doc).trim();

    exports.push(`export const ${constName} = ${JSON.stringify(printed)};`);
  }

  const header = `// Auto-generated by scripts/graphql-emit-documents.mjs - DO NOT EDIT MANUALLY\n\n`;
  fs.writeFileSync(OUT_FILE, header + exports.join("\n\n") + "\n", "utf-8");
  console.log(`[graphql-emit] Emitted ${exports.length} document constants to ${OUT_FILE}`);
}

main();
